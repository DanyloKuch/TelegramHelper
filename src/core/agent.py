def _strip_fence(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        text = text.strip("`")
        if text.lower().startswith("json"):
            text = text[4:]
        text = text.strip()
    return text


def _safe_parse(raw: str) -> dict[str, Any]:
    raw = _strip_fence(raw)
    try:
        parsed = json.loads(raw)
        if isinstance(parsed, dict) and isinstance(parsed.get("intent"), str):
            return parsed
    except Exception:
        logger.warning("agent: bad JSON: %r", raw[:200])
    return {"intent": "unknown"}


async def route_intent(
    provider: LLMProvider,
    user_text: str,
    *,
    heavy: bool = False,
    now_local: str | None = None,
    tz_name: str | None = None,
    history_block: str | None = None,
    quoted_text: str | None = None,
    labels_block: str | None = None,
) -> dict[str, Any]:
    """now_local + tz_name инжектятся в системный промпт, чтобы LLM мог парсить
    относительные даты («завтра в 18:00») в корректный UTC ISO.
    history_block — краткосрочная память диалога владельца с ботом, чтобы понимать
    отсылки вроде «ему», «в том же чате».
    labels_block — список меток чатов владельца (label_chat), нужен для find_and_forward и
    log_to_label, чтобы LLM мог сопоставити узагальнену фразу («моє тренування») з конкретною
    міткою і зрозуміти, чи заданий для неї message_prefix."""
    system = AGENT_SYSTEM
    if now_local and tz_name:
        system = (
            f"Текущее локальное время владельца: {now_local} ({tz_name}).\n"
            f"Когда нужно превратить относительную дату («завтра», «через час», «в пятницу 18:00») "
            f"в ISO-8601, считай в этом TZ и потом конвертируй в UTC.\n\n"
            + system
        )
    if labels_block:
        system = system + "\n\n" + labels_block
    if history_block:
        system = system + "\n\n" + history_block + (
            "\n\nВладелец обычно НЕ отвечает реплаем и не называет заново контакт/чат/тему "
            "каждый раз — он просто продолжает разговор. Короткая или неполная фраза "
            "(«сформулируй тезисы», «сохрани это», «отправь ему», «а теперь то же самое "
            "но короче», «поставь на это напоминание») почти всегда относится к тому, что "
            "он только что говорил/писал — смотри последние реплики владельца в «Недавний "
            "диалог» выше и бери их как предмет запроса. Если там есть на что опереться — "
            "действуй сразу нужным интентом (например: собрал мысли в тезисы — верни их "
            "интентом \"chat\" в поле \"reply\"), НЕ переспрашивай «о чём речь» и не проси "
            "переслать сообщение. Уточняй ТОЛЬКО если история пуста или явно не о том."
        )
    if quoted_text:
        # Реплай на сообщение бота: «распиши это как задачу» без цитаты бессмысленно.
        system = system + (
            "\n\nВЛАДЕЛЕЦ ОТВЕЧАЕТ РЕПЛАЕМ НА ЭТО СООБЩЕНИЕ:\n"
            f'"""\n{quoted_text[:2000]}\n"""\n'
            "Считай цитату частью запроса. Указательные слова («это», «эту задачу», "
            "«сюда», «ось») относятся к ней — не переспрашивай, о чём речь."
        )
    raw = await provider.chat(
        [
            ChatMessage(role="system", content=system),
            ChatMessage(role="user", content=user_text),
        ],
        heavy=heavy,
    )
    return _safe_parse(raw)
